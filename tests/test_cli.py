"""Command line interface (cli.py)."""

from uvbuilder.cli import main
from uvbuilder.models.feynrulesmodel import FeynRulesModel
from uvbuilder.paramCard import ParamCardGenerator
from uvbuilder.models.slhaBuilder import write_card
from tests.test_slhaBuilder import MAJORANA, SDDM_POINT, _sddm_model, _template

PROTOMODEL_DICT = {'masses': {1000022: 100., 1000023: 300., 1000024: 200., 1000025: 400.},
                   'decays': {1000022: {}, 1000023: {(1000022, 23): 1.0},
                              1000024: {(1000022, 24): 1.0}, 1000025: {(1000023, 25): 1.0}}}
# fermionic DM, no charges
PROTOMODEL = dict(PROTOMODEL_DICT, labels={1000022: 'Z1', 1000023: 'Z2', 1000024: 'W1', 1000025: 'Z3'},
                  dm_spin='fermion', dm_charges=['none'])


def _sddm(tmp_path, **options):
    """The SDDM protomodel written to tmp_path/sddm.dict."""
    source = tmp_path / 'sddm.dict'
    source.write_text(repr(dict(PROTOMODEL, **options)))
    return source


def test_build_writes_the_fr_and_pickle_of_each_model(tmp_path, capsys):
    source = _sddm(tmp_path)
    assert main(['build', str(source), '--out', str(tmp_path / 'out')]) == 0
    assert sorted(p.name for p in (tmp_path / 'out' / 'sddm').iterdir()) == ['sddm.fr', 'sddm.md', 'sddm.pkl']
    report = (tmp_path / 'out' / 'sddm' / 'sddm.md').read_text()
    assert '### UMixMZ1Z2Z3: Majorana fermion, Takagi' in report
    assert '| MChiI2Y3ChiI2Ym3 | BSMMASS 2 | mass |' in report and r'M_{\mathrm{ChiI1Y0}}' in report
    assert 'M$ModelName = "sddm";' in (tmp_path / 'out' / 'sddm' / 'sddm.fr').read_text()
    assert '[ChiI1Y0Lw, ChiI2Y3Lw, ChiI2Ym3Lw]' in capsys.readouterr().out



def test_build_author_and_version_from_the_file_or_the_command_line(tmp_path):
    source = _sddm(tmp_path, author='A. Lessa', version='2.0')
    main(['build', str(source), '--out', str(tmp_path / 'file')])
    fr = (tmp_path / 'file' / 'sddm' / 'sddm.fr').read_text()
    assert 'Authors -> {"A. Lessa"}' in fr and 'Version -> "2.0"' in fr
    main(['build', str(source), '-o', str(tmp_path / 'cli'), '--author', 'A', '--author', 'B'])
    fr = (tmp_path / 'cli' / 'sddm' / 'sddm.fr').read_text()
    assert 'Authors -> {"A", "B"}' in fr and 'Version -> "2.0"' in fr
    source = tmp_path / 'default.dict'
    source.write_text(repr(PROTOMODEL_DICT))
    main(['build', str(source), '--out', str(tmp_path / 'default'), '-s', 'fermion'])
    fr = next((tmp_path / 'default').glob('*/*.fr')).read_text()
    assert 'Authors -> {"UVBuilder"}' in fr and 'Version -> "1.0"' in fr
    assert 'automatically generated by UVBuilder' in fr


def test_dict_options_and_their_override_by_the_command_line(tmp_path, capsys):
    data = dict(PROTOMODEL_DICT, name='pm', author=['A', 'B'], version='3.0', dm_spin='fermion',
                dm_charges=['none'])
    (tmp_path / 'sddm.dict').write_text(repr(data))
    fermion = _models(['build', str(tmp_path / 'sddm.dict'), '-s', 'fermion'], capsys)
    assert _models(['build', str(tmp_path / 'sddm.dict')], capsys) == fermion
    assert all(m.startswith('pm') for m in fermion)
    assert _models(['build', str(tmp_path / 'sddm.dict'), '-s', 'both'], capsys) != fermion
    main(['build', str(tmp_path / 'sddm.dict'), '-o', str(tmp_path / 'out'), '--version', '4.0'])
    fr = next((tmp_path / 'out').glob('*/*.fr')).read_text()
    assert 'Authors -> {"A", "B"}' in fr and 'Version -> "4.0"' in fr
    (tmp_path / 'bad.dict').write_text(repr(dict(PROTOMODEL_DICT, dm_spin='vector')))
    assert main(['build', str(tmp_path / 'bad.dict')]) == 1

def test_fill_from_the_pickle_of_build(tmp_path):
    source = _sddm(tmp_path)
    main(['build', str(source), '--out', str(tmp_path)])
    generator = ParamCardGenerator(FeynRulesModel.load(tmp_path / 'sddm' / 'sddm.pkl'))
    template = _template(generator.fr_model, tmp_path / 'template.dat')
    reference = write_card(_sddm_model(MAJORANA), template, tmp_path / 'reference.dat',
                           SDDM_POINT).read_text()
    card = generator.fill(template, SDDM_POINT, tmp_path / 'card.dat')     # inputs set
    assert main(['fill', str(tmp_path / 'sddm' / 'sddm.pkl'), str(card)]) == 0
    assert card.read_text() == reference


def _models(argv, capsys):
    """Names of the models listed by build (the unindented lines of their descriptions)."""
    assert main(argv) == 0
    return [line for line in capsys.readouterr().out.splitlines()
            if line and not line.startswith(' ') and not line.startswith('nothing written')]


def test_build_writes_nothing_without_out(tmp_path, monkeypatch, capsys):
    source = _sddm(tmp_path)
    monkeypatch.chdir(tmp_path)
    assert main(['build', str(source)]) == 0
    out = capsys.readouterr().out
    assert out.startswith('sddm\n') and 'nothing written' in out
    assert '  ChiI2Ym3Lw  LH WeylSpinor  1      2      -1/2' in out
    assert '  W1        Dirac fermion     ChiI2Y3q3 | ChiI2Ym3qm3' in out
    assert '  Z1 Z2 Z3  Majorana fermion  ChiI1Y0q0, ChiI2Y3q0, ChiI2Ym3q0' in out
    assert sorted(p.name for p in tmp_path.iterdir()) == ['sddm.dict']


def test_dm_spins_and_charges_from_the_command_line(tmp_path, capsys):
    from uvbuilder.tools.reps import GlobalU1s
    from uvbuilder.cli import _dm_charges
    assert _dm_charges('none') == GlobalU1s() and _dm_charges('B=0, D=1') == GlobalU1s(B=0, D=1)
    assert _dm_charges('L=1/2') == GlobalU1s(L='1/2')
    source = _sddm(tmp_path)
    fermion = _models(['build', str(source)], capsys)
    scalar = _models(['build', str(source), '--dm-spin', 'scalar'], capsys)
    both = _models(['build', str(source), '--dm-spin', 'both'], capsys)
    assert len(both) == len(fermion) + len(scalar) and scalar
    dark = _models(['build', str(source), '--dm-charges', 'none', '--dm-charges', 'D=1'], capsys)
    assert len(dark) > len(fermion)
    (tmp_path / 'sddm.dict').write_text(repr(PROTOMODEL_DICT))
    assert len(_models(['build', str(tmp_path / 'sddm.dict')], capsys)) == len(both)   # defaults


def test_build_reads_a_dict_file(tmp_path):
    (tmp_path / 'sddm-2.dict').write_text(repr(
        {**PROTOMODEL_DICT, 'xsecs[fb]': {((1000022, 1000023), 13.0): 1.0}, 'walkerid': 'uphi'}))
    assert main(['build', str(tmp_path / 'sddm-2.dict'), '--out', str(tmp_path / 'out')]) == 0
    assert (tmp_path / 'out' / 'sddm_2_1' / 'sddm_2_1.fr').is_file()
    assert (tmp_path / 'out' / 'sddm_2_1' / 'sddm_2_1.pkl').is_file()


def test_build_needs_a_dict_file_with_the_protomodel(tmp_path, capsys):
    (tmp_path / 'model.slha').write_text('BLOCK MASS\n')
    assert main(['build', str(tmp_path / 'model.slha')]) == 1
    assert 'the protomodel is a .dict file' in capsys.readouterr().err
    (tmp_path / 'code.dict').write_text("__import__('os').system('echo hi')")
    assert main(['build', str(tmp_path / 'code.dict')]) == 1
    assert 'is not a dictionary literal' in capsys.readouterr().err


def test_fill_rejects_a_pickle_of_another_object(tmp_path, capsys):
    import pickle
    (tmp_path / 'other.pkl').write_bytes(pickle.dumps({'masses': {}}))
    assert main(['fill', str(tmp_path / 'other.pkl'), str(tmp_path / 'card.dat')]) == 1
    assert 'holds a dict, not a FeynRulesModel' in capsys.readouterr().err


def test_report_writes_real_scalar_blocks_in_the_card_entries():
    from uvbuilder.report import model_report
    from tests.test_slhaBuilder import _sddm_model
    report = model_report(_sddm_model({'PhiI1Y0', 'PhiI2Y3'}))
    assert ': real scalar, orthogonal' in report and '| M² |' in report
    # mu = Rmu + i Imu, no conjugate left
    assert r'\overline' not in report and r'\mathrm{Im}\,\mu_{\mathrm{PhiI1Y0PhiI2Y3}} v' in report
